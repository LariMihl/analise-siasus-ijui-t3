CREATE TABLE `dimtempo` (
  `Id` smallint unsigned NOT NULL AUTO_INCREMENT,
  `di` date NOT NULL,
  `df` date GENERATED ALWAYS AS (last_day(`di`)) STORED,
  `mes` tinyint GENERATED ALWAYS AS (month(`di`)) STORED,
  `mesext` varchar(20) GENERATED ALWAYS AS (date_format(`di`,_utf8mb4'%M')) STORED,
  `ano` smallint GENERATED ALWAYS AS (year(`di`)) STORED,
  `anomes` char(6) GENERATED ALWAYS AS (date_format(`di`,_utf8mb4'%Y%m')) STORED,
  `MAExt` varchar(10) GENERATED ALWAYS AS (concat(date_format(`di`,_utf8mb4'%b'),_utf8mb4'-',date_format(`di`,_utf8mb4'%Y'))) STORED,
  `bimestre` tinyint GENERATED ALWAYS AS ((((month(`di`) - 1) DIV 2) + 1)) STORED,
  `bi_inicio` date GENERATED ALWAYS AS ((makedate(year(`di`),1) + interval (((month(`di`) - 1) DIV 2) * 2) month)) STORED,
  `bi_fim` date GENERATED ALWAYS AS (last_day((`bi_inicio` + interval 1 month))) STORED,
  `biex_t` varchar(20) GENERATED ALWAYS AS (concat((((month(`di`) - 1) DIV 2) + 1),_utf8mb4'º bimestre')) STORED,
  `anobi` char(7) GENERATED ALWAYS AS (concat(year(`di`),_utf8mb4'B',(((month(`di`) - 1) DIV 2) + 1))) STORED,
  `trimestre` tinyint GENERATED ALWAYS AS (quarter(`di`)) STORED,
  `tri_inicio` date GENERATED ALWAYS AS ((makedate(year(`di`),1) + interval ((quarter(`di`) - 1) * 3) month)) STORED,
  `tri_fim` date GENERATED ALWAYS AS (last_day((`tri_inicio` + interval 2 month))) STORED,
  `triex_t` varchar(20) GENERATED ALWAYS AS (concat(quarter(`di`),_utf8mb4'º trimestre')) STORED,
  `anotri` char(7) GENERATED ALWAYS AS (concat(year(`di`),_utf8mb4'T',quarter(`di`))) STORED,
  `semestre` tinyint GENERATED ALWAYS AS ((((month(`di`) - 1) DIV 6) + 1)) STORED,
  `sem_inicio` date GENERATED ALWAYS AS ((makedate(year(`di`),1) + interval (((month(`di`) - 1) DIV 6) * 6) month)) STORED,
  `sem_fim` date GENERATED ALWAYS AS (last_day((`sem_inicio` + interval 5 month))) STORED,
  `semex_t` varchar(20) GENERATED ALWAYS AS (concat((((month(`di`) - 1) DIV 6) + 1),_utf8mb4'º semestre')) STORED,
  `anosem` char(7) GENERATED ALWAYS AS (concat(year(`di`),_utf8mb4'S',(((month(`di`) - 1) DIV 6) + 1))) STORED,
  PRIMARY KEY (`Id`),
  UNIQUE KEY `uq_dimtempo_di` (`di`),
  KEY `ix_anomes` (`anomes`),
  KEY `ix_anobi` (`anobi`),
  KEY `ix_anotri` (`anotri`),
  KEY `ix_anosem` (`anosem`)
) ENGINE=InnoDB AUTO_INCREMENT=204 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
